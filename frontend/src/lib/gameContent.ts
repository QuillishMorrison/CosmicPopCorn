export function moduleCostForLevel(baseCost: ModuleCatalogItem['buildCost'], nextLevel: number) {
  const multiplier = 1 + (nextLevel - 1) * 0.45
  return Object.entries(baseCost).map(([resource, value]) => ({
    resource,
    amount: Math.round(value * multiplier)
  }))
}
